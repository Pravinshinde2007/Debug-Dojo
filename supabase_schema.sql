-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Case-insensitive unique index for emails
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON public.users (lower(trim(email)));

-- 2. User Tokens Table
CREATE TABLE IF NOT EXISTS public.user_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    revoked INTEGER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS user_tokens_token_idx ON public.user_tokens(token);
CREATE INDEX IF NOT EXISTS user_tokens_user_id_idx ON public.user_tokens(user_id);

-- 3. Sandbox Attempts Table
CREATE TABLE IF NOT EXISTS public.sandbox_attempts (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    problem_title TEXT,
    problem_statement TEXT,
    problem_spec TEXT,
    language TEXT DEFAULT 'python',
    code TEXT,
    mode TEXT,
    passed INTEGER DEFAULT 0 NOT NULL,
    test_results TEXT,
    feedback TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS sandbox_attempts_user_id_idx ON public.sandbox_attempts(user_id);
CREATE INDEX IF NOT EXISTS sandbox_attempts_created_at_idx ON public.sandbox_attempts(created_at DESC);

-- 4. Submissions Table
CREATE TABLE IF NOT EXISTS public.submissions (
    id TEXT PRIMARY KEY,
    learner_id TEXT,
    challenge_id TEXT,
    code TEXT,
    visible_results TEXT,
    hidden_results TEXT,
    mistake_tags TEXT,
    explanation TEXT,
    passed INTEGER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS submissions_learner_idx ON public.submissions(learner_id);
CREATE INDEX IF NOT EXISTS submissions_challenge_idx ON public.submissions(challenge_id);

-- 5. Hints Given Table
CREATE TABLE IF NOT EXISTS public.hints_given (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id TEXT,
    learner_id TEXT,
    hint_index INTEGER,
    hint_text TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS hints_given_sub_idx ON public.hints_given(submission_id);

-- 6. Learner Events Table
CREATE TABLE IF NOT EXISTS public.learner_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id TEXT,
    event_type TEXT,
    payload TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS learner_events_learner_idx ON public.learner_events(learner_id);

-- 7. LLM Log Table
CREATE TABLE IF NOT EXISTS public.llm_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt TEXT,
    response TEXT,
    context TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ============================================================================
-- Row Level Security (RLS) Configuration
-- Ensure API access works seamlessly with anon and service_role keys
-- ============================================================================

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sandbox_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hints_given ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.learner_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.llm_log ENABLE ROW LEVEL SECURITY;

-- Permissive policies for PostgREST API
DO $$
BEGIN
    DROP POLICY IF EXISTS "Public access users" ON public.users;
    CREATE POLICY "Public access users" ON public.users FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access tokens" ON public.user_tokens;
    CREATE POLICY "Public access tokens" ON public.user_tokens FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access sandbox" ON public.sandbox_attempts;
    CREATE POLICY "Public access sandbox" ON public.sandbox_attempts FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access submissions" ON public.submissions;
    CREATE POLICY "Public access submissions" ON public.submissions FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access hints" ON public.hints_given;
    CREATE POLICY "Public access hints" ON public.hints_given FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access events" ON public.learner_events;
    CREATE POLICY "Public access events" ON public.learner_events FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access llm" ON public.llm_log;
    CREATE POLICY "Public access llm" ON public.llm_log FOR ALL USING (true) WITH CHECK (true);
END $$;
